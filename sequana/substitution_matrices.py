class SubstitutionMatrix:
    """A symmetric amino-acid (or nucleotide) substitution/scoring matrix.

    Wraps a dict of pairwise substitution scores (e.g. BLOSUM62, PAM250) and
    exposes a simple ``score(a, b)`` lookup used by pairwise aligners.

    Args:
        name: matrix name (e.g. "BLOSUM62")
        scores: dict mapping (char_a, char_b) -> score, symmetric lookups are
            handled automatically (score("A","R") == score("R","A"))

    Example::

        from sequana.substitution_matrices import load_matrix
        m = load_matrix("BLOSUM62")
        m.score("A", "A")
        4
        m.score("W", "F")
        1
    """

    def __init__(self, name: str, scores: Dict[Tuple[str, str], float]):
        self.name = name
        self._scores = scores
        self.alphabet = sorted({a for a, _ in scores} | {b for _, b in scores})

    def score(self, a: str, b: str) -> float:
        """Return substitution score between two residues/bases.

        Unknown characters (not in the matrix alphabet) default to the
        matrix's minimum score, a conservative choice that penalizes
        ambiguous/unexpected letters instead of raising.
        """
        a = a.upper()
        b = b.upper()
        try:
            return self._scores[(a, b)]
        except KeyError:
            try:
                return self._scores[(b, a)]
            except KeyError:
                return min(self._scores.values())

    def __repr__(self) -> str:
        return f"SubstitutionMatrix({self.name}, {len(self.alphabet)} symbols)"


def _expand(raw_pairs):
    """Expand a compact upper-triangular pair list into a full symmetric dict."""
    scores = {}
    for a, b, s in raw_pairs:
        scores[(a, b)] = s
        scores[(b, a)] = s
    return scores


def available_matrices():
    """Return the list of built-in substitution matrix names."""
    return sorted(_RAW_MATRICES.keys())


def load_matrix(name: str) -> SubstitutionMatrix:
    """Load a built-in substitution matrix by name.

    Args:
        name: one of :func:`available_matrices`, e.g. "BLOSUM62", "PAM250".

    Returns:
        SubstitutionMatrix instance.

    Raises:
        ValueError: if ``name`` is not a known built-in matrix.

    Example::

        from sequana.substitution_matrices import load_matrix
        blosum62 = load_matrix("BLOSUM62")
    """
    name = name.upper()
    if name not in _RAW_MATRICES:
        raise ValueError(f"Unknown substitution matrix {name!r}. Available: {available_matrices()}")
    return SubstitutionMatrix(name, _expand(_RAW_MATRICES[name]))


def simple_dna_matrix(match: float = 1.0, mismatch: float = -1.0) -> SubstitutionMatrix:
    """Build a trivial match/mismatch scoring matrix for nucleotides (ACGTN).

    Useful default for DNA/RNA pairwise alignment where a full substitution
    matrix like BLOSUM (protein-oriented) doesn't apply.

    Example::

        from sequana.substitution_matrices import simple_dna_matrix
        m = simple_dna_matrix(match=2, mismatch=-1)
        m.score("A", "A")
        2
        m.score("A", "T")
        -1
    """
    bases = "ACGTN"
    scores = {}
    for a in bases:
        for b in bases:
            scores[(a, b)] = match if a == b else mismatch
    return SubstitutionMatrix("DNA_SIMPLE", scores)
